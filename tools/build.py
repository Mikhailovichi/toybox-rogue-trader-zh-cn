def plain(value):
    return TAG.sub("", value)


def styled(key, translation):
    if TAG.search(translation):
        return translation
    single_span = re.fullmatch(
        r"((?:<(?:b|i|color|size)(?:=[^>]+)?>)+)[^<]*((?:</(?:b|i|color|size)>)+)",
        key,
    )
    if single_span:
        return single_span[1].replace("<color=##", "<color=#") + translation + single_span[2]
    return translation


def build():
    data = json.loads(BASELINE.read_text(encoding="utf-8-sig"))
    original = data["Strings"]
    result = {}
    changes = []
    for index, (key, value) in enumerate(original.items()):
        translated = styled(key, REVISIONS[index]) if index in REVISIONS else value
        result[key] = translated
        if translated != value:
            changes.append({"key": key, "before": value, "after": translated})
    by_plain = {}
    for key, value in result.items():
        normalized = plain(key)
        by_plain.setdefault(normalized, value)
        if not TAG.search(key):
            by_plain[normalized] = value
    additions = json.loads((PROJECT / "tools/additions.json").read_text(encoding="utf-8"))
    extracted = json.loads((PROJECT / "reference/extracted-keys.json").read_text(encoding="utf-8"))
    finite = json.loads((PROJECT / "reference/finite-keys.json").read_text(encoding="utf-8"))
    for key in sorted(set(extracted["keys"]) | set(extracted["named_filters"]) | set(finite)):
        if key in result:
            continue
        normalized = plain(key)
        if normalized in additions:
            result[key] = styled(key, additions[normalized])
        elif normalized in by_plain:
            result[key] = styled(key, by_plain[normalized])
        else:
            raise ValueError(f"Missing reviewed translation: {key!r}")
    for key, translated in additions.items():
        if key not in result:
            result[key] = translated
    data["LanguageCode"] = "zh-CN"
    data["Version"] = "1.7.34"
    data["Contributors"] = "ohZbs, Kirie, lhr7324925, mitcheese"
    data["HomePage"] = "https://github.com/xADDBx/ToyBox-RogueTrader"
    data["Strings"] = dict(sorted(result.items()))
    (PROJECT / "Localization/zh-CN.json").write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8",
    )
    (PROJECT / "docs/translation-review.json").write_text(
        json.dumps({
            "baseline_reviewed": len(original),
            "revised": len(changes),
            "added": len(result) - len(original),
            "total": len(result),
            "changes": changes,
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8",
    )
    print(f"Reviewed {len(original)}, revised {len(changes)}, added {len(result)-len(original)}, total {len(result)}")


if __name__ == "__main__":
    build()
